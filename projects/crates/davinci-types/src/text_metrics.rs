const UNITS_PER_EM: f64 = 2048.0;
/// Fallback advance for codepoints missing from the table (the space advance
/// of the source font).
const DEFAULT_ADVANCE: f64 = 617.0;
/// Full-width advance for CJK codepoints, per the documented convention.
const FULL_WIDTH_ADVANCE: f64 = UNITS_PER_EM;

fn is_full_width(c: char) -> bool {
    matches!(c as u32,
        0x1100..=0x11FF | 0x2E80..=0x9FFF | 0xA000..=0xA4CF | 0xAC00..=0xD7AF
        | 0xF900..=0xFAFF | 0xFE30..=0xFE4F | 0xFF00..=0xFF60 | 0xFFE0..=0xFFE6 | 0x3000..=0x303F)
}

fn advance_of(c: char) -> f64 {
    if is_full_width(c) {
        return FULL_WIDTH_ADVANCE;
    }
    match ADVANCES.binary_search_by_key(&(c as u32), |(codepoint, _)| *codepoint) {
        Ok(index) => ADVANCES[index].1 as f64,
        Err(_) => DEFAULT_ADVANCE,
    }
}

/// Measure a single line of label text at the given font size.
pub fn measure_line(text: &str, font_size: f64) -> f64 {
    text.chars().map(advance_of).sum::<f64>() * font_size / UNITS_PER_EM
}

/// Greedy label wrapping: words stay together while they fit, overlong words
/// split by character, and content beyond `max_lines` folds into the last
/// line, which is truncated with a trailing ellipsis that fits `max_width`.
pub fn wrap_label(text: &str, font_size: f64, max_width: f64, max_lines: usize) -> Vec<String> {
    let mut lines: Vec<String> = Vec::new();
    for authored in text.split('\n') {
        let mut current = String::new();
        for word in authored.split(' ') {
            let candidate = if current.is_empty() { word.to_string() } else { format!("{current} {word}") };
            if measure_line(&candidate, font_size) <= max_width {
                current = candidate;
                continue;
            }
            if !current.is_empty() {
                lines.push(std::mem::take(&mut current));
            }
            if measure_line(word, font_size) <= max_width {
                current = word.to_string();
                continue;
            }
            for character in word.chars() {
                let mut candidate = current.clone();
                candidate.push(character);
                if measure_line(&candidate, font_size) <= max_width {
                    current = candidate;
                }
                else {
                    if !current.is_empty() {
                        lines.push(std::mem::take(&mut current));
                    }
                    current = character.to_string();
                }
            }
        }
        lines.push(std::mem::take(&mut current));
    }
    if lines.len() <= max_lines {
        return lines;
    }
    let mut kept: Vec<String> = lines.drain(..max_lines).collect();
    let overflow = lines.join(" ");
    let mut last = kept.pop().unwrap_or_default();
    if !overflow.is_empty() {
        last = if last.is_empty() { overflow } else { format!("{last} {overflow}") };
    }
    kept.push(truncate_with_ellipsis(&last, font_size, max_width));
    kept
}

/// Truncate a line so that the kept prefix plus `…` fits `max_width`.
fn truncate_with_ellipsis(line: &str, font_size: f64, max_width: f64) -> String {
    let ellipsis_width = advance_of('…') * font_size / UNITS_PER_EM;
    let mut kept = String::new();
    for character in line.chars() {
        let candidate_width = measure_line(&kept, font_size) + advance_of(character) * font_size / UNITS_PER_EM + ellipsis_width;
        if candidate_width > max_width {
            break;
        }
        kept.push(character);
    }
    kept.push('…');
    kept
}